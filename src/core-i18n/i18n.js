const MESSAGES = { en, zh, ta, ms, hi };

function readStoredLanguage() {
    try {
        const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
        if (LANGUAGES.some((lang) => lang.id === saved)) return saved;
    } catch {
        /* ignore */
    }
    return 'en';
}

function formatMessage(template, vars) {
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (_, key) => (vars[key] == null ? '' : String(vars[key])));
}

const LanguageContext = createContext({
    language: 'en',
    setLanguage: () => {},
    t: (key) => key,
});

export function LanguageProvider({ children }) {
    const [language, setLanguageState] = useState(readStoredLanguage);

    const setLanguage = (next) => {
        if (!LANGUAGES.some((lang) => lang.id === next)) return;
        setLanguageState(next);
        try {
            localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
        } catch {
            /* ignore */
        }
    };

    useEffect(() => {
        const meta = LANGUAGES.find((lang) => lang.id === language);
        document.documentElement.lang = meta?.htmlLang || 'en';
    }, [language]);

    const value = useMemo(() => {
        const table = MESSAGES[language] || en;
        const t = (key, vars) => {
            const template = table[key] ?? en[key] ?? key;
            return formatMessage(template, vars);
        };
        return { language, setLanguage, t };
    }, [language]);

    return React.createElement(LanguageContext.Provider, { value }, children);
}

export function useLanguage() {
    return useContext(LanguageContext);
}
