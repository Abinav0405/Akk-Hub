function extractKeys(block) {
  const out = {};
  for (const m of block.matchAll(/'([^']+)':\s*"((?:\\.|[^"\\])*)"/g)) {
    out[m[1]] = m[2].replace(/\\"/g, '"').replace(/\\n/g, '\n');
  }
  return out;
}

function buildBlock(keys) {
  return Object.entries(keys)
    .map(([k, v]) => {
      const esc = String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
      return `    '${k}': "${esc}",`;
    })
    .join('\n')
    .replace(/,$/, ''); // last comma handled by next line in file — keep trailing commas on all
}

function buildBlockWithCommas(keys) {
  return Object.entries(keys)
    .map(([k, v]) => {
      const esc = String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
      return `    '${k}': "${esc}",`;
    })
    .join('\n');
}

function replaceHub(src, marker, hubBlock) {
  const idx = src.indexOf(marker);
  if (idx < 0) throw new Error('marker not found ' + marker);
  const hubStart = src.indexOf("    'hub.brand':", idx);
  const themeLine = src.indexOf("    'hub.theme.system':", hubStart);
  if (hubStart < 0 || themeLine < 0) throw new Error('hub block not found for ' + marker);
  const endLine = src.indexOf('\n', themeLine);
  return src.slice(0, hubStart) + hubBlock + src.slice(endLine);
}

function currentHubKeys(src, marker) {
  const idx = src.indexOf(marker);
  const hubStart = src.indexOf("    'hub.brand':", idx);
  const endLine = src.indexOf('\n', src.indexOf("    'hub.theme.system':", hubStart));
  return extractKeys(src.slice(hubStart, endLine));
}

